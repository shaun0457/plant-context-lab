// Build: typecheck, inline the engine and the UI strings into index.html, bundle the Node server,
// regenerate docs/rules.md from the engine, and record an input hash.
//
//   npm run build
import { execFileSync } from 'node:child_process';
import { createHash } from 'node:crypto';
import { mkdirSync, readdirSync, readFileSync, statSync, writeFileSync } from 'node:fs';
import { dirname, join, relative } from 'node:path';
import { fileURLToPath, pathToFileURL } from 'node:url';
import { build } from 'esbuild';

const root = join(dirname(fileURLToPath(import.meta.url)), '..');
const rel = (p) => join(root, p);
const MARK = '/*__PCL_ENGINE__*/';
const MARK_I18N = '/*__PCL_I18N__*/';
const BS = String.fromCharCode(92); // backslash

function walk(dir) {
  return readdirSync(dir).flatMap((f) => {
    const p = join(dir, f);
    return statSync(p).isDirectory() ? walk(p) : [p];
  });
}

/** sha256 over the build inputs; test/build-fresh.test.ts recomputes it. */
export function inputHash() {
  const files = [...walk(rel('src')), rel('web/index.template.html')]
    .filter((p) => /\.(ts|json|html)$/.test(p))
    .map((p) => relative(root, p).split('\\').join('/'))
    .sort();
  const h = createHash('sha256');
  for (const f of files) {
    h.update(f + '\0');
    h.update(readFileSync(join(root, f), 'utf8').replace(/\r\n/g, '\n'));
    h.update('\0');
  }
  return h.digest('hex');
}

async function main() {
  // 1. typecheck
  execFileSync(process.execPath, [rel('node_modules/typescript/bin/tsc'), '--noEmit', '-p', root], { stdio: 'inherit' });

  // 2. engine IIFE inlined into the static page
  const eng = await build({
    entryPoints: [rel('src/engine/index.ts')],
    bundle: true,
    format: 'iife',
    globalName: 'PCL',
    platform: 'browser',
    target: ['es2018'],
    minify: true,
    legalComments: 'none',
    charset: 'utf8',
    write: false,
  });
  const js = eng.outputFiles[0].text.trim();
  if (/<\/script/i.test(js)) throw new Error('engine bundle contains a closing script tag');
  if (js.includes('<!--')) throw new Error('engine bundle contains an HTML comment opener');
  if (/https?:/i.test(js)) throw new Error('engine bundle contains an http(s) URL');
  const tpl = readFileSync(rel('web/index.template.html'), 'utf8');
  if (tpl.split(MARK).length !== 2) throw new Error('template must contain exactly one ' + MARK);
  if (tpl.split(MARK_I18N).length !== 2) throw new Error('template must contain exactly one ' + MARK_I18N);
  // UI strings (en / zh) as a JSON literal; '<' is escaped so no string can close the script tag
  const S = await import(pathToFileURL(rel('src/page/strings.ts')).href);
  const i18n = 'var PCL_I18N=' + JSON.stringify(S.STRINGS).split('<').join(BS + 'u003c') + ';';
  const html = tpl.replace(MARK_I18N, () => i18n).replace(MARK, () => js);
  if (/https?:/i.test(html)) throw new Error('index.html would contain an http(s) URL');
  writeFileSync(rel('index.html'), html);

  // 3. Node package (bin): dependencies stay external
  mkdirSync(rel('dist'), { recursive: true });
  await build({
    entryPoints: [rel('src/server/main.ts')],
    outfile: rel('dist/server.js'),
    bundle: true,
    format: 'esm',
    platform: 'node',
    target: ['node22'],
    packages: 'external',
    banner: { js: '#!/usr/bin/env node' },
    legalComments: 'none',
    charset: 'utf8',
  });

  // 4. docs/rules.md generated from the engine (single source of truth)
  const E = await import(pathToFileURL(rel('src/engine/index.ts')).href);
  const rows = E.RULES.map((r) => {
    const src = r.source.knowledge ? r.source.knowledge + ' (' + r.source.review + '); ' + r.source.publication : 'derived from ' + r.source.derivedFrom + ' (demo convention, not a published limit)';
    return '| `' + r.id + '` | `' + r.signal + '` | ' + r.kind + ' | ' + r.comparator + ' ' + r.value + ' ' + r.unit + ' | ' + r.state + ' | ' + src + ' |';
  });
  const G = E.GATE_PARAMS;
  const md = [
    '# Rules and gate parameters',
    '',
    '<!-- generated by scripts/build.mjs from src/engine/rules.ts and src/engine/gate.ts; do not edit by hand -->',
    '',
    'States: NORMAL < ATTENTION < ALARM < TRIP. A signal takes the state of the most severe rule it triggers.',
    '',
    '| Rule id | Signal | Kind | Condition | State | Source |',
    '|---|---|---|---|---|---|',
    ...rows,
    '',
    'Every other process signal has **no reviewed limit** and is reported as such, never guessed. `XMEAS(21)` has an explicit reviewed statement that its alarm and shutdown limits are unspecified (`' + E.KR.row3.id + '`).',
    '',
    'Limits left out on purpose: Downs & Vogel (1993) also lists level constraints for the reactor, separator and stripper. They are not in the reviewed knowledge revision, their shutdown values are volumes that need an unsourced conversion to the % measurement, and the lumped model does not simulate levels.',
    '',
    '## Gate parameters',
    '',
    '| Parameter | Value |',
    '|---|---|',
    '| XMV range | ' + G.xmvMin + '–' + G.xmvMax + ' % |',
    '| Max step per action | ' + G.maxStepPct + ' %-points |',
    '| Rate limit | ' + G.maxChangeInWindowPct + ' %-points of applied change per XMV per ' + G.rateWindowMin + ' simulated min |',
    '| Simulate-before-act horizon | ' + G.horizonMin + ' simulated min (branch copy, same noise as the live plant) |',
    '| Rule check | reject if the branch with the change reaches ALARM or TRIP; if the plant reaches ALARM/TRIP anyway without the change, reject only if the change makes the worst state or any ruled peak worse (so corrective moves stay possible) |',
    '| Headroom check | reject if the peak of a ruled signal rises by more than ' + G.maxHeadroomLossFraction * 100 + ' % of its nominal headroom versus no change (demo convention) |',
    '| SPE check | reject if mean SPE rises by more than ' + G.speMarginOfLimit + ' x SPE limit versus no change and ends above the limit |',
    '| Rationale | required, max ' + G.rationaleMaxLen + ' characters |',
    '| Adjustable XMVs | ' + E.MODELLED_XMVS.join(', ') + ' |',
    '',
    'Reason codes: XMV_UNKNOWN, XMV_NOT_MODELLED, TARGET_INVALID, TARGET_OUT_OF_RANGE, RATIONALE_MISSING, TRIP_ACTIVE, STEP_TOO_LARGE, RATE_LIMIT, SIM_RULE_TRIP, SIM_RULE_ALARM, SIM_HEADROOM_LOSS, PCA_SPE_WORSENS.',
    '',
  ].join('\n');
  writeFileSync(rel('docs/rules.md'), md);

  // 5. input hash for the freshness test
  writeFileSync(rel('dist/build-info.json'), JSON.stringify({ inputs: inputHash(), engineBytes: js.length, indexBytes: html.length }, null, 2) + '\n');

  process.stdout.write('built index.html (' + (html.length / 1024).toFixed(1) + ' KB, engine ' + (js.length / 1024).toFixed(1) + ' KB), dist/server.js, docs/rules.md\n');
}

if (import.meta.url === pathToFileURL(process.argv[1]).href) {
  main().catch((e) => { process.stderr.write(String(e && e.stack || e) + '\n'); process.exit(1); });
}
